function buildPermissions(): PermissionRow[] {
  const actions = Object.values(Action)
  const rows: PermissionRow[] = []
  let id = 1
  for (let resourceId = 1; resourceId <= 20; resourceId++) {
    for (const action of actions) {
      rows.push({
        id: id++,
        resource_id: resourceId,
        action,
        created_at: now,
      })
    }
  }
  return rows
}

/** Super Admin gets ORGANIZATION scope on every permission */
export function buildSuperAdminRolePermissions(
  permissions: PermissionRow[],
  orgScopeId = 5,
): RolePermissionRow[] {
  return permissions.map((p) => ({
    role_id: 1,
    permission_id: p.id,
    scope_id: orgScopeId,
    created_at: now,
    changed_by: 1,
  }))
}

